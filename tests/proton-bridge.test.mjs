import assert from 'node:assert/strict';
import {mkdtemp,writeFile,readFile,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {prepareSteamProtonBridge,acceptSteamProtonBridge} from '../src/linux-proton-bridge.mjs';
const base=await mkdtemp(join(tmpdir(),'melty-bridge-test-'));
process.env.XDG_DATA_HOME=join(base,'data');
const peak=join(base,'Steam','steamapps','common','PEAK');
const l4d=join(base,'Steam','steamapps','common','Left 4 Dead 2');
await mkdir(peak,{recursive:true}); await mkdir(l4d,{recursive:true});
await writeFile(join(peak,'winhttp.dll'),'mod');
let out=await prepareSteamProtonBridge({appId:3527290,vars:{DEADASCENT_L4D2_DIR:l4d, MELTY_SESSION_ID:'test session',BAD__KEY:'a\nwrong'},gameDir:peak});
assert.equal(out.confirmed,false);
assert(out.launchOptions.endsWith('3527290 %command%'));
let conf=await readFile(out.configPath,'utf8');
assert(conf.includes('WINEDLLOVERRIDES'));
assert(conf.includes('Z:\\'));
assert(!conf.includes('BAD__KEY'));
const got=execFileSync('/bin/sh',['-c',`"${out.binary}" 3527290 /usr/bin/env`],{encoding:'utf8',env:{...process.env,HOME:base}});
assert(got.includes('DEADASCENT_L4D2_DIR=Z:\\'));
assert(got.includes('WINEDLLOVERRIDES=winhttp=n,b'));
await acceptSteamProtonBridge(out);
out=await prepareSteamProtonBridge({appId:3527290,vars:{DEADASCENT_L4D2_DIR:l4d, MELTY_SESSION_ID:'session two'},gameDir:peak});
assert.equal(out.confirmed,true);
assert((await readFile(out.configPath,'utf8')).includes('session two'));
console.log('PASS native Steam wrapper: env forward, Windows path, winhttp override, update, approval');
